class HamInfoPage extends StatelessWidget {
  const HamInfoPage({super.key, required this.info});

  final HamInfo info;

  static Future<void> open(BuildContext context, HamInfo info) =>
      Navigator.of(context).push(MaterialPageRoute<void>(builder: (_) => HamInfoPage(info: info)));

  @override
  Widget build(BuildContext context) {
    final k = HamTokens.of(context);
    final doc = switch (info) {
      HamInfo.offer => _offer,
      HamInfo.terms => _terms,
      HamInfo.privacy => _privacy,
    };
    return Scaffold(
      appBar: AppBar(title: Text(info.shortTitle)),
      body: SelectionArea(
        child: ListView(
          padding: const EdgeInsets.fromLTRB(14, 20, 14, 40),
          children: [
            Padding(
              padding: const EdgeInsets.symmetric(horizontal: 4),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(doc.title, style: TextStyle(color: k.text, fontSize: 20, fontWeight: FontWeight.w800, height: 1.3)),
                  const Gap(6),
                  Text(doc.date, style: TextStyle(color: k.textDim, fontSize: 13)),
                  const Gap(14),
                ],
              ),
            ),
            for (final s in doc.sections)
              HamCard(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(s.title, style: TextStyle(color: k.text, fontSize: 17, fontWeight: FontWeight.w700)),
                    const Gap(10),
                    for (final p in s.paragraphs) ...[
                      Padding(
                        padding: EdgeInsets.only(left: p.startsWith('• ') ? 8 : 0),
                        child: Text(p, style: TextStyle(color: k.text, fontSize: 15, height: 1.55)),
                      ),
                      const Gap(8),
                    ],
                  ],
                ),
              ),
          ],
        ),
      ),
    );
  }
}
